    @EnvironmentObject private var library: LibraryStore

    var body: some View {
        List {
            Section {
                Text("黑白键AI-你的陪练搭子")
                    .font(.headline)
                Text("隐私政策 · 更新日期：2026 年 10 月 11 日")
                    .font(.footnote)
                    .foregroundStyle(.secondary)
                Text("NoteLite 提供识谱、改谱和谱面导出，NoteWise 在设备上聆听演奏。本版本支持配置的 HTTPS 云端识谱、账户同步和课堂作业；请在上传前确认服务地址与课堂分享范围。")
            }

            Section("保存在设备上的内容") {
                Text("导入的乐谱副本、生成或下载的结果、曲谱列表和任务信息保存在应用存储中。已填写的服务器地址保存在应用设置中；访问令牌按服务器分别保存在此设备的系统钥匙串中。")
                Text("练习记录保留当时的曲谱、练习时间、时长、输入能力、逐音证据和待复核结果。未登录时保存在本机；登录后，个人曲谱快照、计时和分析版本同步到当前账户，以便多端读取。不同账户的个人记录分别存储，不会因切换账户而上传到另一个账户。系统备份及你选用的文件服务由相应服务提供方管理。")
            }

            if library.hasLocalEngine {
                Section("本机识谱") {
                    Text("已有本机识谱入口使用随应用附带的 NoteLite 引擎及资源，在设备上处理原稿并生成 MusicXML 和 MIDI。云端入口仅上传你主动选择的原稿；本机处理失败不会自动上传。")
                    Text("引擎可能在应用存储中保存配置、临时文件、运行日志和错误信息，用于本机处理与排错，不会自动发送给开发者。完成的任务会尝试清理工作文件；中断、超时或异常时可能留下部分文件。")
                }
            }

            Section("麦克风与 MIDI") {
                Text("点击开始麦克风练习后，应用才会请求系统权限并在本机分析、保存演奏录音；MIDI 音符也在本机处理。结束练习、离开页面或应用进入后台时停止输入。录音不会自动上传；只有你在提交课堂作业时明确勾选或选择录音，才会上传并分享给该课堂教师。")
                Text("你可以在系统设置中撤销麦克风权限，也可以使用已连接的 MIDI 乐器练习。")
            }

            Section("云端识谱与账户同步") {
                Text("你主动导入识谱时，PDF 或图片原稿及文件名通过 HTTPS 发给配置的服务器。查询、修改和导出请求发送任务标识及认证信息。注册与登录发送用户名、密码和设备名称；服务存储密码校验值与账户、会话标识，认证令牌保存在设备钥匙串中。服务器可看到 IP 地址等连接信息。")
                Text("原稿可能包含姓名、批注或图片元数据，应用不会在上传前自动去除这些内容。仅导入文件不会启动识谱上传；MusicXML 可直接在本机练习。")
                Text("检查连接会访问所填服务器的健康检查接口，不发送原稿或访问令牌。已有任务在回到前台后可能继续查询和下载，仍使用原来的服务器。暂停跟踪不会取消服务器正在执行的识谱。")
            }

            Section("课堂与练习分析") {
                Text("加入课堂不会自动分享个人练习历史。只有你确认提交作业后，该课堂教师才可查看选定记录、固定的分析版本和你附上的录音。以后追加的分析版本不会自动改写旧作业提交。")
                Text("点击 AI 分析后，服务从你选择的练习记录生成受控的汇总事实，再发送给 DeepSeek 生成说明；不向模型发送原始录音、MusicXML、逐音数组、账户密码或访问令牌。没有练习记录时不能分析。模型说明不会把未知或待复核演奏当作正确结果。")
            }

            Section("保留与删除") {
                Text("本机曲谱、独立练习历史、录音、账户同步副本与课堂提交分别保留。删除一份本机曲谱或退出账户不会同时删除其他位置的内容；退出账户会清除当前登录凭据并隐藏该账户的私人内容。")
                if library.hasLocalEngine {
                    Text("删除曲谱不会同时清空独立保存的引擎配置、日志或异常遗留的工作文件。当前版本没有单独清空这些引擎数据的按钮。")
                }
                Text("本仓库的桥接服务默认保留原稿、结果、任务状态和引擎日志，直到清理完成，没有自动到期删除。其他服务器的保留时间、日志和备份由运营者决定；需要进一步删除时请联系该运营者。上传中断后，服务器可能仍保留已接收的文件。")
                Text("可在账户设备管理中撤销会话，也可退出当前账户。需要进一步删除账户、历史、录音或课堂已经分享的副本时，请联系服务运营者。删除设备上的应用数据不会自动清理服务器、系统备份或已分享的副本。")
            }

            Section("分享与第三方服务") {
                Text("仅当你使用系统分享功能时，所选文件会交给你选择的应用或服务。支持链接在外部浏览器或邮件应用打开，其数据处理遵循对应服务的政策。")
                Text("客户端没有广告追踪、跨应用追踪或出售用户数据的功能。课堂提交和 AI 汇总分析按上述说明处理；其他自选服务器由相应运营者管理。")
            }

            Section("联系与政策更新") {
                Text("开发维护：Yuexuan Zhang（Lucas0623z）。如需询问隐私或报告问题，可通过以下方式联系。请勿在公开问题中提交访问令牌、私人乐谱或其他敏感信息。")
                Link("隐私联系：Lucas.z0623@outlook.com", destination: AppSupport.emailURL)
                Link("支持与问题反馈", destination: AppSupport.issuesURL)
                Text("数据处理方式改变时，我们会更新本政策及日期。")
                    .foregroundStyle(.secondary)
            }
        }
        .textSelection(.enabled)
        .navigationTitle("隐私政策")
        .noteLiteInlineTitle()
        .tint(NoteLiteTheme.accent)
    }
}
