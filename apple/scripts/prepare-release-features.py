#!/usr/bin/env python3
"""Generate/verify compiled release policy from the single versioned source.

No environment variable, local preference or server response enables purchases.
This release deliberately has no transaction implementation.
"""
import argparse
import hashlib
import json
from pathlib import Path


def prepare(check=False):
    root = Path(__file__).resolve().parents[2]
    source = root / "config/release-features.json"
    raw = source.read_bytes()
    config = json.loads(raw)
    if config["schemaVersion"] != 1 or config["releaseStage"] != "testflight" or config["inAppPurchases"] is not False:
        raise ValueError("Purchases must remain disabled for this release")
    digest = hashlib.sha256(raw).hexdigest()
    quote = lambda value: json.dumps(value, ensure_ascii=False)
    ts = f'''// Generated by apple/scripts/prepare-release-features.py; edit config/release-features.json.
export const releaseFeatures = Object.freeze({{
  releaseStage: {quote(config['releaseStage'])},
  inAppPurchases: false as boolean,
  purchaseUnavailableMessage: {quote(config['purchaseUnavailableMessage'])},
  sourceSHA256: {quote(digest)},
}});
export const paidActionTokens: readonly string[] = Object.freeze({quote(config['paidActionTokens'])});
export const paidRootTokens: readonly string[] = Object.freeze({quote(config['paidRootTokens'])});
'''
    swift = f'''// Generated by apple/scripts/prepare-release-features.py; edit config/release-features.json.
import Foundation

enum ReleaseFeatures {{
    static let releaseStage = {quote(config['releaseStage'])}
    static let inAppPurchases = false
    static let purchaseUnavailableMessage = {quote(config['purchaseUnavailableMessage'])}
    static let sourceSHA256 = {quote(digest)}
    private static let paidActionTokens: Set<String> = {quote(config['paidActionTokens'])}
    private static let paidRootTokens: Set<String> = {quote(config['paidRootTokens'])}

    static func isPaidRequest(_ action: String, payload: [String: Any] = [:]) -> Bool {{
        func paid(_ value: String) -> Bool {{
            let path = value.lowercased().prefix(while: {{ $0 != "?" && $0 != "#" }})
            let components = path.split(separator: "/").map(String.init)
            let route = components.drop(while: {{ ["api", "account"].contains($0) }})
            return route.contains(where: {{ paidActionTokens.contains($0) }}) ||
                route.first.map {{ paidRootTokens.contains($0) }} == true
        }}
        return paid(action) || (payload["path"] as? String).map(paid) == true
    }}

    static func requireAllowedRequest(_ action: String, payload: [String: Any] = [:]) throws {{
        if !inAppPurchases && isPaidRequest(action, payload: payload) {{
            throw CloudOMRError(code: "purchase_unavailable", message: purchaseUnavailableMessage)
        }}
    }}

    static func performPurchase<T>(_ transaction: () throws -> T) throws -> T {{
        guard inAppPurchases else {{
            throw CloudOMRError(code: "purchase_unavailable", message: purchaseUnavailableMessage)
        }}
        return try transaction()
    }}
}}
'''
    outputs = {root / "figma-ui/src/app/release-features.ts": ts,
               root / "apple/NoteLite/ReleaseFeatures.swift": swift}
    for target, value in outputs.items():
        if check:
            if not target.is_file() or target.read_text(encoding="utf8") != value:
                raise ValueError(f"Generated release policy differs: {target.relative_to(root)}")
        else:
            target.write_text(value, encoding="utf8", newline="\n")
    return {"status": "passed", "inAppPurchases": False, "releaseStage": config["releaseStage"],
            "sourceSHA256": digest, "generatedFiles": len(outputs)}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    print(json.dumps(prepare(parser.parse_args().check)))
